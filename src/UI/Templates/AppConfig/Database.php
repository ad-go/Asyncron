        // Found live 2026-08-19: Settings, Queue, and DbSync all share this
        // one SQLite file, and the NAT-safe remote-test relay's incoming
        // pull-test-requests traffic goes through the global
        // SessionInvalidationFilter, which reads Settings on every
        // request - a concurrent burst produced real "database is locked"
        // errors that stalled the relay for minutes. busyTimeout (retry
        // instead of failing immediately) plus WAL mode on the actual .db
        // file once it exists (see enableSqliteWalMode(), called from the
        // writable/ permissions step below) resolved it - verified live,
        // zero lock errors across a 6-request concurrent burst afterward.
